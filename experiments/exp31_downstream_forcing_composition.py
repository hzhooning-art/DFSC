"""Downstream SciML task with an unknown forcing correction.

This experiment tests the primitive-level claim in a setting closer to a
downstream SciML workflow. The target field is generated by a known fractional
Mittag-Leffler backbone plus an unmodeled, input-dependent forcing correction.
The hybrid model receives the MLSL backbone and learns only the correction,
whereas pure neural baselines learn the full map from ``(u0, t)`` to ``u(t)``.
"""

from __future__ import annotations

import csv
import json
import math
import sys
import time
from pathlib import Path

import torch
from torch import nn

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from dfsc import DeepONet1D, FNO1D, MLSLConfig, build_dirichlet_mlsl_1d


RESULTS = ROOT / "results"
TABLES = RESULTS / "tables"


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        f = path.open("w", newline="", encoding="utf-8")
    except PermissionError:
        path = path.with_name(f"{path.stem}_{int(time.time())}{path.suffix}")
        f = path.open("w", newline="", encoding="utf-8")
    with f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print("Saved:", path)


def rel(pred: torch.Tensor, target: torch.Tensor) -> float:
    return (torch.linalg.norm(pred - target) / torch.linalg.norm(target).clamp_min(1e-14)).item()


def make_random_initial_conditions(x: torch.Tensor, count: int, max_mode: int = 8) -> torch.Tensor:
    coeffs = torch.randn(count, max_mode, dtype=x.dtype) / torch.arange(1, max_mode + 1, dtype=x.dtype)
    modes = torch.stack([torch.sin((i + 1) * torch.pi * x) for i in range(max_mode)])
    fields = coeffs @ modes
    return fields / torch.linalg.norm(fields, dim=1, keepdim=True).clamp_min(1e-12)


def forcing_amplitude(u0: torch.Tensor, x: torch.Tensor) -> torch.Tensor:
    probe = torch.sin(2.0 * torch.pi * x)
    return 0.8 + 0.35 * torch.tanh(6.0 * torch.mean(u0 * probe, dim=-1))


def target_from_backbone(
    u0_batch: torch.Tensor,
    times: torch.Tensor,
    x: torch.Tensor,
    layer,
    alpha: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    rows_u0, rows_t, rows_backbone, rows_target, rows_amp = [], [], [], [], []
    amp = forcing_amplitude(u0_batch, x)
    spatial_forcing = torch.sin(torch.pi * x) + 0.35 * torch.sin(3.0 * torch.pi * x)
    for u0, a in zip(u0_batch, amp, strict=True):
        backbone = layer(u0, times, alpha).detach()
        t_col = times[:, None]
        correction = 0.55 * a * times.pow(alpha)[:, None] * spatial_forcing[None, :]
        correction = correction + 0.12 * a * t_col * backbone.pow(2)
        target = backbone + correction
        rows_u0.append(u0[None, :].expand(times.numel(), -1))
        rows_t.append(times)
        rows_backbone.append(backbone)
        rows_target.append(target)
        rows_amp.append(a.expand(times.numel()))
    return (
        torch.cat(rows_u0),
        torch.cat(rows_t),
        torch.cat(rows_backbone),
        torch.cat(rows_target),
        torch.cat(rows_amp),
    )


class ForcingResidualHead(nn.Module):
    """Residual head that learns the unmodeled forcing around an MLSL backbone."""

    def __init__(self, hidden: int = 64) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(5, hidden),
            nn.GELU(),
            nn.Linear(hidden, hidden),
            nn.GELU(),
            nn.Linear(hidden, 1),
        )

    def forward(
        self,
        backbone: torch.Tensor,
        u0: torch.Tensor,
        x: torch.Tensor,
        t: torch.Tensor,
        amp: torch.Tensor,
    ) -> torch.Tensor:
        batch, n = backbone.shape
        x_grid = x[None, :].expand(batch, -1)
        t_grid = t[:, None].expand_as(backbone)
        amp_grid = amp[:, None].expand_as(backbone)
        features = torch.stack(
            [
                backbone.reshape(-1),
                u0.reshape(-1),
                x_grid.reshape(-1),
                t_grid.reshape(-1),
                amp_grid.reshape(-1),
            ],
            dim=-1,
        )
        return self.net(features).squeeze(-1).reshape_as(backbone)


def run_seed(seed: int) -> list[dict[str, object]]:
    torch.manual_seed(8100 + seed)
    torch.set_default_dtype(torch.float64)

    x, layer = build_dirichlet_mlsl_1d(
        num_points=48,
        num_modes=18,
        config=MLSLConfig.stable(terms=120),
    )
    alpha_true = torch.tensor(1.18)
    train_times = torch.linspace(0.0, 0.08, 7)
    test_times = torch.linspace(0.14, 0.34, 7)
    train_u0 = make_random_initial_conditions(x, 24)
    test_u0 = make_random_initial_conditions(x, 8)

    train_u0_rows, train_t_rows, train_backbone, train_y, train_amp = target_from_backbone(
        train_u0, train_times, x, layer, alpha_true
    )
    test_u0_rows, test_t_rows, test_backbone, test_y, test_amp = target_from_backbone(
        test_u0, test_times, x, layer, alpha_true
    )

    rows: list[dict[str, object]] = []

    rows.append(
        {
            "seed": seed,
            "model": "MLSL_backbone_only",
            "train_relative_error": rel(train_backbone, train_y),
            "long_time_relative_error": rel(test_backbone, test_y),
        }
    )

    residual = ForcingResidualHead().to(dtype=torch.float64)
    opt_hybrid = torch.optim.Adam(residual.parameters(), lr=2e-3)
    for _ in range(360):
        opt_hybrid.zero_grad()
        correction = residual(train_backbone, train_u0_rows, x, train_t_rows, train_amp)
        pred = train_backbone + correction
        loss = torch.mean((pred - train_y) ** 2)
        loss.backward()
        opt_hybrid.step()
    hybrid_train = (train_backbone + residual(train_backbone, train_u0_rows, x, train_t_rows, train_amp)).detach()
    hybrid_test = (test_backbone + residual(test_backbone, test_u0_rows, x, test_t_rows, test_amp)).detach()
    rows.append(
        {
            "seed": seed,
            "model": "Hybrid_MLSL_unknown_forcing",
            "train_relative_error": rel(hybrid_train, train_y),
            "long_time_relative_error": rel(hybrid_test, test_y),
        }
    )

    fno = FNO1D(modes=12, width=36, layers=3).to(dtype=torch.float64)
    opt_fno = torch.optim.Adam(fno.parameters(), lr=2e-3)
    for _ in range(140):
        opt_fno.zero_grad()
        pred = fno(train_u0_rows, train_t_rows)
        loss = torch.mean((pred - train_y) ** 2)
        loss.backward()
        opt_fno.step()
    rows.append(
        {
            "seed": seed,
            "model": "FNO1D_width36_modes12",
            "train_relative_error": rel(fno(train_u0_rows, train_t_rows).detach(), train_y),
            "long_time_relative_error": rel(fno(test_u0_rows, test_t_rows).detach(), test_y),
        }
    )

    x_train = x[None, :].expand(train_u0_rows.shape[0], -1)
    t_train = train_t_rows[:, None].expand(-1, x.numel())
    x_test = x[None, :].expand(test_u0_rows.shape[0], -1)
    t_test = test_t_rows[:, None].expand(-1, x.numel())
    deeponet = DeepONet1D(num_points=x.numel(), latent=72, hidden=112).to(dtype=torch.float64)
    opt_deep = torch.optim.Adam(deeponet.parameters(), lr=1e-3)
    y_mean = train_y.mean()
    y_std = train_y.std().clamp_min(1e-12)
    train_y_norm = (train_y - y_mean) / y_std
    alpha_train = alpha_true.expand(train_u0_rows.shape[0])
    alpha_test = alpha_true.expand(test_u0_rows.shape[0])
    for _ in range(160):
        opt_deep.zero_grad()
        pred = deeponet(train_u0_rows, x_train, t_train, alpha_train)
        loss = torch.mean((pred - train_y_norm) ** 2)
        loss.backward()
        opt_deep.step()
    deep_train = (deeponet(train_u0_rows, x_train, t_train, alpha_train) * y_std + y_mean).detach()
    deep_test = (deeponet(test_u0_rows, x_test, t_test, alpha_test) * y_std + y_mean).detach()
    rows.append(
        {
            "seed": seed,
            "model": "DeepONet_latent72_hidden112",
            "train_relative_error": rel(deep_train, train_y),
            "long_time_relative_error": rel(deep_test, test_y),
        }
    )

    return rows


def main() -> None:
    all_rows: list[dict[str, object]] = []
    for seed in [0, 1, 2]:
        all_rows.extend(run_seed(seed))
    write_csv(TABLES / "downstream_forcing_composition.csv", all_rows)

    summary: dict[str, float] = {}
    for model in sorted({str(row["model"]) for row in all_rows}):
        vals = [float(row["long_time_relative_error"]) for row in all_rows if row["model"] == model]
        train_vals = [float(row["train_relative_error"]) for row in all_rows if row["model"] == model]
        mean_val = sum(vals) / len(vals)
        std_val = math.sqrt(sum((v - mean_val) ** 2 for v in vals) / max(len(vals) - 1, 1))
        summary[f"{model}_long_time_error_mean"] = mean_val
        summary[f"{model}_long_time_error_std"] = std_val
        summary[f"{model}_train_error_mean"] = sum(train_vals) / len(train_vals)
    (RESULTS / "downstream_forcing_composition_summary.json").write_text(
        json.dumps(summary, indent=2),
        encoding="utf-8",
    )
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
